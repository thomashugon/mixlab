"""MixLab ↔ YouTube Music bridge.

A long-lived helper started by the Electron main process. It speaks JSON lines:
  stdin  → {"id": 1, "cmd": "playlists", "args": {...}}
  stdout ← {"id": 1, "ok": true, "result": ...} | {"id": 1, "ok": false, "error": "..."}
  stdout ← {"event": "download", ...}            (unsolicited progress events)

ytmusicapi reads the library (browser authentication from pasted request headers);
yt-dlp fetches the audio of a track into an .m4a file, using the same cookies, which
the main process then imports like any local file.

Environment:
  MIXLAB_YTM_DIR     folder holding browser.json, cookies.txt and the audio files
  MIXLAB_FFMPEG_DIR  folder containing ffmpeg/ffprobe (for yt-dlp post-processing)
  MIXLAB_DENO        path of the deno binary used by yt-dlp to solve YouTube's JS challenges
  MIXLAB_YTM_FAKE    "1" → offline fake backend (tests only)
"""

import json
import os
import re
import shutil
import subprocess
import sys
import threading
import time
import traceback
from concurrent.futures import ThreadPoolExecutor

BASE = os.environ.get("MIXLAB_YTM_DIR") or os.path.join(os.path.expanduser("~"), ".mixlab-ytmusic")
AUTH_FILE = os.path.join(BASE, "browser.json")
COOKIE_FILE = os.path.join(BASE, "cookies.txt")
AUDIO_DIR = os.path.join(BASE, "audio")
FFMPEG_DIR = os.environ.get("MIXLAB_FFMPEG_DIR") or None
DENO = os.environ.get("MIXLAB_DENO") or None
FAKE = os.environ.get("MIXLAB_YTM_FAKE") == "1"

_out_lock = threading.Lock()


def emit(obj):
    line = json.dumps(obj, ensure_ascii=False)
    with _out_lock:
        sys.stdout.write(line + "\n")
        sys.stdout.flush()


class UserError(Exception):
    """An error whose message is shown as-is to the user (in French)."""


# ---------------------------------------------------------------- helpers

def parse_headers(raw):
    """Parse request headers copied from the browser's dev tools.

    Accepts the classic "Name: value" form (Firefox, Chrome "raw") and Chrome's
    newer layout where each name and value sits on its own line.
    """
    headers = {}
    pending = None  # name waiting for its value on the next line ("" = HTTP/2 pseudo header, dropped)
    for line in raw.replace("\r\n", "\n").split("\n"):
        s = line.strip()
        if not s:
            continue
        if pending is not None:
            if pending:
                headers[pending] = s
            pending = None
            continue
        name_only = re.match(r"^(:?)([A-Za-z0-9-]+):$", s)
        if name_only:
            pending = "" if name_only.group(1) else name_only.group(2).lower()
            continue
        if s.startswith(":"):  # ":authority: music.youtube.com"
            continue
        m = re.match(r"^([A-Za-z0-9-]+):\s*(.*)$", s)
        if m:
            headers[m.group(1).lower()] = m.group(2)
    return headers


def cookie_jar_text(cookie_header):
    """Netscape cookie file for yt-dlp built from a Cookie request header."""
    expiry = int(time.time()) + 365 * 24 * 3600
    lines = ["# Netscape HTTP Cookie File", "# Generated by MixLab from your YouTube Music session", ""]
    for part in cookie_header.split(";"):
        if "=" not in part:
            continue
        name, value = part.strip().split("=", 1)
        if not name:
            continue
        lines.append("\t".join([".youtube.com", "TRUE", "/", "TRUE", str(expiry), name, value]))
    return "\n".join(lines) + "\n"


def best_thumb(thumbs):
    if not thumbs:
        return None
    t = max(thumbs, key=lambda x: (x.get("width") or 0) * (x.get("height") or 0))
    url = t.get("url")
    # lh3.googleusercontent.com thumbnails can be resized with a suffix.
    if url and "googleusercontent.com" in url:
        url = re.sub(r"=w\d+-h\d+.*$", "=w544-h544-l90-rj", url)
    return url


def audio_path(video_id):
    return os.path.join(AUDIO_DIR, f"{video_id}.m4a")


def norm_track(t):
    vid = t.get("videoId")
    if not vid:
        return None
    artists = ", ".join(a.get("name", "") for a in (t.get("artists") or []) if a.get("name"))
    album = (t.get("album") or {}).get("name", "") if isinstance(t.get("album"), dict) else ""
    dur = t.get("duration_seconds")
    if dur is None and t.get("duration"):
        try:
            parts = [int(x) for x in str(t["duration"]).split(":")]
            dur = 0
            for p in parts:
                dur = dur * 60 + p
        except ValueError:
            dur = None
    return {
        "videoId": vid,
        "title": t.get("title") or vid,
        "artists": artists,
        "album": album,
        "duration": dur,
        "thumbnail": best_thumb(t.get("thumbnails")),
        "available": t.get("isAvailable", True) is not False,
        "downloaded": os.path.exists(audio_path(vid)),
    }


# ---------------------------------------------------------------- real backend

class Backend:
    def __init__(self):
        self._yt = None

    def yt(self):
        if self._yt is None:
            if not os.path.exists(AUTH_FILE):
                raise UserError("Non connecté à YouTube Music.")
            from ytmusicapi import YTMusic
            self._yt = YTMusic(AUTH_FILE, language="fr", location="FR")
        return self._yt

    def status(self):
        return {"connected": os.path.exists(AUTH_FILE), "audioDir": AUDIO_DIR}

    def login(self, headers_raw):
        headers = parse_headers(headers_raw)
        missing = [h for h in ("cookie", "x-goog-authuser") if h not in headers]
        if missing:
            raise UserError(
                "En-têtes incomplets : il manque " + ", ".join(missing) +
                ". Copiez les en-têtes d'une requête « browse » vers music.youtube.com (voir l'aide).")
        if "SAPISID" not in headers["cookie"] and "__Secure-3PAPISID" not in headers["cookie"]:
            raise UserError("Le cookie ne contient pas de session Google : vérifiez que vous êtes connecté sur music.youtube.com.")
        from ytmusicapi import setup
        os.makedirs(BASE, exist_ok=True)
        tmp = AUTH_FILE + ".tmp"
        # ytmusicapi expects "name: value" lines; rebuild them from the parsed dict.
        setup(filepath=tmp, headers_raw="\n".join(f"{k}: {v}" for k, v in headers.items()))
        from ytmusicapi import YTMusic
        yt = YTMusic(tmp, language="fr", location="FR")
        try:
            info = yt.get_account_info()
        except Exception as e:
            os.remove(tmp)
            raise UserError("YouTube Music a refusé ces en-têtes (session expirée ou incomplète). Détail : " + str(e))
        os.replace(tmp, AUTH_FILE)
        with open(COOKIE_FILE, "w", encoding="utf-8") as f:
            f.write(cookie_jar_text(headers["cookie"]))
        os.chmod(AUTH_FILE, 0o600)
        os.chmod(COOKIE_FILE, 0o600)
        self._yt = yt
        return {"name": info.get("accountName") or "", "handle": info.get("channelHandle") or "", "photo": info.get("accountPhotoUrl")}

    def logout(self):
        for p in (AUTH_FILE, COOKIE_FILE):
            if os.path.exists(p):
                os.remove(p)
        self._yt = None
        return True

    def account(self):
        info = self.yt().get_account_info()
        return {"name": info.get("accountName") or "", "handle": info.get("channelHandle") or "", "photo": info.get("accountPhotoUrl")}

    def playlists(self):
        out = []
        for p in self.yt().get_library_playlists(limit=None):
            pid = p.get("playlistId")
            if not pid:
                continue
            out.append({"id": pid, "title": p.get("title") or "", "count": p.get("count"), "thumbnail": best_thumb(p.get("thumbnails"))})
        return out

    def playlist(self, pid):
        if pid == "LM":
            data = self.yt().get_liked_songs(limit=5000)
        else:
            data = self.yt().get_playlist(pid, limit=None)
        tracks = [x for x in (norm_track(t) for t in data.get("tracks") or []) if x]
        return {"title": data.get("title") or "", "tracks": tracks}

    def search(self, q):
        res = self.yt().search(q, filter="songs", limit=40)
        return [x for x in (norm_track(t) for t in res) if x]

    def download(self, track, on_progress, cancelled):
        import yt_dlp

        os.makedirs(AUDIO_DIR, exist_ok=True)
        vid = track["videoId"]
        final = audio_path(vid)
        if os.path.exists(final):
            return final
        tmpdir = os.path.join(AUDIO_DIR, ".part")
        os.makedirs(tmpdir, exist_ok=True)

        def hook(d):
            if cancelled():
                raise yt_dlp.utils.DownloadCancelled("Annulé")
            if d.get("status") == "downloading":
                total = d.get("total_bytes") or d.get("total_bytes_estimate") or 0
                if total:
                    on_progress(min(0.95, d.get("downloaded_bytes", 0) / total * 0.95))

        opts = {
            # 141 = AAC 256 kb/s (Premium), 140 = AAC 128 kb/s.
            "format": "141/140/bestaudio[ext=m4a]/bestaudio",
            "outtmpl": os.path.join(tmpdir, "%(id)s.%(ext)s"),
            "noplaylist": True,
            "quiet": True,
            "no_warnings": True,
            "noprogress": True,
            "progress_hooks": [hook],
            "postprocessors": [{"key": "FFmpegExtractAudio", "preferredcodec": "m4a"}],
            "retries": 3,
            "fragment_retries": 3,
        }
        if os.path.exists(COOKIE_FILE):
            # Work on a copy: yt-dlp rewrites the cookie file it is given.
            jar = os.path.join(tmpdir, f"{vid}.cookies.txt")
            shutil.copyfile(COOKIE_FILE, jar)
            opts["cookiefile"] = jar
        if FFMPEG_DIR:
            opts["ffmpeg_location"] = FFMPEG_DIR
        if DENO:
            opts["js_runtimes"] = {"deno": {"path": DENO}}
        try:
            with yt_dlp.YoutubeDL(opts) as ydl:
                ydl.extract_info(f"https://music.youtube.com/watch?v={vid}", download=True)
        finally:
            jar = opts.get("cookiefile")
            if jar and os.path.exists(jar):
                os.remove(jar)
        produced = os.path.join(tmpdir, f"{vid}.m4a")
        if not os.path.exists(produced):
            raise UserError("yt-dlp n'a pas produit de fichier audio.")
        tag_file(produced, track)
        os.replace(produced, final)
        return final


def tag_file(path, track):
    """Write the YouTube Music metadata (cleaner than the video's) and the square cover."""
    try:
        from mutagen.mp4 import MP4, MP4Cover
    except ImportError:
        return
    try:
        f = MP4(path)
        f["\xa9nam"] = [track.get("title") or ""]
        if track.get("artists"):
            f["\xa9ART"] = [track["artists"]]
        if track.get("album"):
            f["\xa9alb"] = [track["album"]]
        f["\xa9cmt"] = [f"YouTube Music {track['videoId']}"]
        url = track.get("thumbnail")
        if url:
            try:
                import requests
                r = requests.get(url, timeout=15)
                if r.ok and r.content:
                    fmt = MP4Cover.FORMAT_PNG if r.content[:4] == b"\x89PNG" else MP4Cover.FORMAT_JPEG
                    f["covr"] = [MP4Cover(r.content, imageformat=fmt)]
            except Exception:
                pass
        f.save()
    except Exception:
        traceback.print_exc(file=sys.stderr)


