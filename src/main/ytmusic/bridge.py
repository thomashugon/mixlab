# ---------------------------------------------------------------- downloads

class Downloads:
    def __init__(self, backend):
        self.backend = backend
        self.pool = ThreadPoolExecutor(max_workers=2)
        self.cancel_gen = 0

    def enqueue(self, tracks):
        gen = self.cancel_gen
        for t in tracks:
            emit({"event": "download", "videoId": t["videoId"], "status": "queued", "progress": 0})
            self.pool.submit(self._run, t, gen)
        return len(tracks)

    def cancel(self):
        self.cancel_gen += 1
        return True

    def _run(self, track, gen):
        vid = track["videoId"]
        cancelled = lambda: gen != self.cancel_gen
        if cancelled():
            emit({"event": "download", "videoId": vid, "status": "cancelled"})
            return
        emit({"event": "download", "videoId": vid, "status": "downloading", "progress": 0})
        last = [0.0]

        def prog(p):
            if p - last[0] >= 0.04:
                last[0] = p
                emit({"event": "download", "videoId": vid, "status": "downloading", "progress": round(p, 3)})

        try:
            path = self.backend.download(track, prog, cancelled)
            emit({"event": "download", "videoId": vid, "status": "done", "progress": 1, "path": path})
        except Exception as e:
            if cancelled():
                emit({"event": "download", "videoId": vid, "status": "cancelled"})
            else:
                emit({"event": "download", "videoId": vid, "status": "error", "error": friendly(e)})


def friendly(e):
    if isinstance(e, UserError):
        return str(e)
    msg = re.sub(r"\x1b\[[0-9;]*m", "", str(e)).strip()
    msg = re.sub(r"^ERROR:\s*", "", msg)
    low = msg.lower()
    if "sign in to confirm" in low or "cookies" in low and "invalid" in low:
        return "YouTube demande une nouvelle connexion : reconnectez-vous à YouTube Music dans MixLab."
    if "video unavailable" in low or "not available" in low:
        return "Morceau indisponible sur YouTube Music."
    if "403" in low or "nsig" in low or "signature" in low or "challenge" in low:
        return "YouTube a bloqué le téléchargement. Mettez yt-dlp à jour (bouton « Mettre à jour ») puis réessayez. Détail : " + msg[:200]
    return msg[:400] or e.__class__.__name__


# ---------------------------------------------------------------- main loop

def main():
    # Pipes default to the locale's encoding (cp1252 on Windows): titles need UTF-8.
    sys.stdin.reconfigure(encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    backend =FakeBackend() if FAKE else Backend()
    downloads = Downloads(backend)
    emit({"event": "ready", "fake": FAKE})
    handlers = {
        "status": lambda a: backend.status(),
        "login": lambda a: backend.login(a.get("headers", "")),
        "logout": lambda a: backend.logout(),
        "account": lambda a: backend.account(),
        "playlists": lambda a: backend.playlists(),
        "playlist": lambda a: backend.playlist(a["id"]),
        "search": lambda a: backend.search(a.get("q", "")),
        "download": lambda a: downloads.enqueue(a.get("tracks", [])),
        "cancel": lambda a: downloads.cancel(),
        "versions": lambda a: versions(),
    }
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            msg = json.loads(line)
        except json.JSONDecodeError:
            continue
        rid = msg.get("id")

        def work(msg=msg, rid=rid):
            try:
                fn = handlers.get(msg.get("cmd"))
                if not fn:
                    raise UserError(f"Commande inconnue : {msg.get('cmd')}")
                emit({"id": rid, "ok": True, "result": fn(msg.get("args") or {})})
            except Exception as e:
                if not isinstance(e, UserError):
                    traceback.print_exc(file=sys.stderr)
                emit({"id": rid, "ok": False, "error": friendly(e)})

        # Library requests can take a few seconds: answer them off the read loop.
        threading.Thread(target=work, daemon=True).start()


def versions():
    out = {}
    try:
        import ytmusicapi
        out["ytmusicapi"] = getattr(ytmusicapi, "__version__", "?")
    except ImportError:
        pass
    try:
        from yt_dlp.version import __version__
        out["yt-dlp"] = __version__
    except ImportError:
        pass
    return out


if __name__ == "__main__":
    main()
